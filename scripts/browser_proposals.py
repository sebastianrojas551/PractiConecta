from pathlib import Path

Path(".local-check").mkdir(exist_ok=True)
from playwright.sync_api import sync_playwright, expect
from uuid import uuid4
suffix=uuid4().hex[:10]
with sync_playwright() as p:
 browser=p.chromium.launch(channel='msedge',headless=True)
 company=browser.new_page(); student=browser.new_page()
 def register(page,role):
  email=f'{role}-{suffix}@example.com'
  page.goto('http://localhost:5174')
  page.get_by_role('button',name='Crear una cuenta',exact=True).click()
  page.get_by_label('Tipo de cuenta').select_option(role)
  page.get_by_label('Nombre del representante' if role=='empresa' else 'Nombre completo').fill('Prueba navegador '+role)
  page.get_by_label('Correo electrónico').fill(email)
  page.get_by_label('Contraseña',exact=True).fill('Clave ficticia navegador 2026')
  page.get_by_role('button',name='Crear cuenta',exact=True).click()
  expect(page.get_by_role('button',name='Cerrar sesión',exact=True)).to_be_visible()
  page.get_by_role('button',name='Cerrar sesión',exact=True).click()
  page.get_by_label('Correo electrónico').fill(email)
  page.get_by_label('Contraseña',exact=True).fill('Clave ficticia navegador 2026')
  page.get_by_role('button',name='Ingresar',exact=True).click()
  expect(page.get_by_role('button',name='Cerrar sesión',exact=True)).to_be_visible()
  print('PASS registro/login '+role,flush=True)
 register(company,'empresa');register(student,'estudiante')
 form=company.locator('form.offer-form')
 for label,value in [('Título','Oferta navegador '+suffix),('Área','Tecnología'),('Descripción','Desarrollo de una aplicación de prueba'),('Requisitos','Conocimientos de Python'),('Horas de práctica','280')]: form.get_by_label(label,exact=True).fill(value)
 form.get_by_role('button',name='Publicar oferta',exact=True).click()
 expect(company.get_by_role('heading',name='Oferta navegador '+suffix,exact=True)).to_be_visible()
 assert company.get_by_role('alert').count()==0, company.get_by_role('alert').all_text_contents()
 student.reload()
 card=student.locator('article.offer').filter(has=student.get_by_role('heading',name='Oferta navegador '+suffix,exact=True))
 card.get_by_role('button',name='Postular',exact=True).click()
 expect(card.get_by_role('button',name='Ya postulaste')).to_be_disabled()
 company.locator('article.offer').filter(has=company.get_by_role('heading',name='Oferta navegador '+suffix,exact=True)).get_by_role('button',name='Ver postulaciones').click()
 expect(company.get_by_text('Prueba navegador estudiante',exact=True)).to_be_visible()
 company.screenshot(path='.local-check/browser-company.png',full_page=True)
 student.screenshot(path='.local-check/browser-student.png',full_page=True)
 print('PASS publicación/postulación y consulta empresarial',flush=True)
 company.get_by_label('Razón social',exact=True).fill('Empresa ficticia navegador')
 company.get_by_label('RUT de la empresa',exact=True).fill('12.345.678-5')
 company.get_by_role('button',name='Guardar perfil',exact=True).click()
 expect(company.get_by_role('status').first).to_contain_text('guardado')
 company.get_by_role('button',name='Preparar propuesta',exact=True).click()
 form=company.get_by_role('region',name='Preparar propuesta',exact=True)
 form.get_by_label('Fecha de inicio',exact=True).fill('2027-01-04')
 form.get_by_label('Fecha de término',exact=True).fill('2027-03-31')
 form.get_by_label('Horas acordadas',exact=True).fill('280')
 form.get_by_label('Condiciones de la propuesta',exact=True).fill('Desarrollo web, horario de lunes a viernes. Datos ficticios.')
 form.get_by_role('button',name='Enviar propuesta',exact=True).click()
 cp=company.get_by_role('region',name='Propuestas de práctica',exact=True)
 expect(cp.get_by_role('heading',name='Oferta navegador '+suffix,exact=True)).to_be_visible()
 student.get_by_role('button',name='Actualizar propuestas',exact=True).click()
 sp=student.get_by_role('region',name='Propuestas de práctica',exact=True)
 expect(student.get_by_role('button',name='Retirar',exact=True)).to_have_count(0)
 sp.get_by_role('button',name='Aceptar propuesta',exact=True).click()
 expect(sp.get_by_text('aceptada',exact=True)).to_be_visible()
 sp.get_by_label('Respaldo privado (PDF, máximo 2 MiB)',exact=True).set_input_files({'name':'respaldo-ficticio.pdf','mimeType':'application/pdf','buffer':b'%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF'})
 sp.get_by_role('button',name='Guardar respaldo',exact=True).click()
 expect(sp.get_by_role('link',name='Descargar respaldo privado',exact=True)).to_be_visible()
 sp.get_by_label('Estado informado').select_option('autorizacion_informada')
 sp.get_by_label('Observaciones sobre autorización',exact=True).fill('Declaración ficticia para prueba')
 sp.get_by_role('button',name='Guardar declaración',exact=True).click()
 expect(sp.locator('p').filter(has_text='Declaración ficticia para prueba')).to_be_visible()
 company.get_by_role('button',name='Actualizar propuestas',exact=True).click()
 cp.get_by_role('button',name='Emitir carta empresarial',exact=True).click()
 expect(cp.get_by_role('link',name='Descargar carta empresarial (HTML imprimible)',exact=True)).to_be_visible()
 student.get_by_role('button',name='Actualizar propuestas',exact=True).click()
 with student.expect_download() as info:
  sp.get_by_role('link',name='Descargar carta empresarial (HTML imprimible)',exact=True).click()
 downloaded=info.value
 downloaded.save_as('.local-check/carta-navegador.html')
 assert 'Empresa ficticia navegador' in open('.local-check/carta-navegador.html',encoding='utf-8').read()
 company.screenshot(path='.local-check/proposals-company.png',full_page=True)
 student.screenshot(path='.local-check/proposals-student.png',full_page=True)
 print('PASS propuesta, aceptación, respaldo privado, declaración y carta empresarial',flush=True)
 browser.close()
